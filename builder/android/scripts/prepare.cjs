'use strict';

/**
 * Developer-only Android QA app generator.
 * Inputs come from an authorized GitHub Actions manual run or local CLI.
 * NEVER expose this generator as a public unmetered build API.
 */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const net = require('node:net');
const { createPng, isValidPng256 } = require('../../windows/scripts/icon.cjs');

const ACCENTS = Object.freeze({
  blue: '#3478f6',
  violet: '#825df5',
  mint: '#168f91',
  rose: '#d85f89'
});
const ORIENTATIONS = Object.freeze({
  auto: 'unspecified',
  portrait: 'portrait'
});

function validateUrl(raw) {
  if(typeof raw!=='string'||raw.length>2048)throw Error('Website URL is missing or too long.');
  let u;
  try {u=new URL(raw.trim());}
  catch {throw Error('Enter a complete public https:// website URL.');}
  const host=u.hostname.toLowerCase().replace(/^\[|\]$/g,'');
  if(u.protocol!=='https:'||u.username||u.password||u.port||net.isIP(host)||!host.includes('.')||
     host.endsWith('.')||
     /(?:^|\.)(?:localhost|local|internal|lan|home|test|invalid|onion|arpa)$/i.test(host)||
     /[\s\\]/.test(raw))throw Error('Only public HTTPS domains without custom ports are allowed in this QA builder.');
  u.hash='';
  return u.href;
}

function validateName(raw) {
  if(typeof raw!=='string')throw Error('App name must be text.');
  if(/[\r\n\0]/.test(raw))throw Error('App name must be a single line.');
  const name=raw.trim().replace(/\s+/g,' ');
  if(name.length<2||name.length>36||!/^[A-Za-z0-9][A-Za-z0-9 ._-]*$/.test(name)||/[. ]$/.test(name)){
    throw Error('QA app name: 2–36 ASCII letters/numbers, spaces, dots, hyphens or underscores.');
  }
  return name;
}

function validateAccent(raw) {
  if(!Object.hasOwn(ACCENTS,raw))throw Error('Choose blue, violet, mint or rose.');
  return ACCENTS[raw];
}

function validateOrientation(raw) {
  if(!Object.hasOwn(ORIENTATIONS,raw))throw Error('Orientation must be auto or portrait.');
  return ORIENTATIONS[raw];
}

function applicationIdFor(rawUrl) {
  const url=validateUrl(rawUrl);
  const suffix=crypto.createHash('sha256').update(new URL(url).origin).digest('hex').slice(0,20);
  // Android package names are ASCII and segments must start with letters.
  return 'com.warpvio.qa.s'+suffix;
}

function parseCli(argv) {
  const options=new Set(['url','name','accent','orientation','icon']);
  const parsed={};
  if(argv.length%2)throw Error('All flags require a value.');
  for(let i=0;i<argv.length;i+=2){
    const key=argv[i],value=argv[i+1];
    if(!key?.startsWith('--')||!options.has(key.slice(2))||value?.startsWith('--')||parsed[key.slice(2)]!==undefined){
      throw Error('Invalid flags: use --url --name --accent --orientation [--icon].');
    }
    parsed[key.slice(2)]=value;
  }
  return parsed;
}

function propertiesEscape(value) {
  // java.util.Properties.load(InputStream) decodes ISO-8859-1. For the QA
  // builder only ASCII configuration is accepted; escape control characters
  // and disallow multiline values to avoid injecting Gradle properties.
  const s=String(value);
  if(!/^[\x20-\x7E]*$/.test(s))throw Error('Only printable ASCII configuration is supported.');
  return s.replace(/\\/g,'\\\\');
}

function generate(input,baseDir=path.resolve(__dirname,'..')) {
  const websiteUrl=validateUrl(input.url);
  const appName=validateName(input.name);
  const accent=typeof input.accent==='string'?input.accent:'blue';
  const accentColor=validateAccent(accent);
  const orientation=typeof input.orientation==='string'?input.orientation:'auto';
  const nativeOrientation=validateOrientation(orientation);
  const applicationId=applicationIdFor(websiteUrl);

  const letter=appName[0].toUpperCase();
  let icon;
  if(input.icon) {
    const iconPath=path.resolve(input.icon);
    const info=fs.statSync(iconPath);
    if(!info.isFile()||info.size>4*1024*1024)throw Error('Custom icon exceeds size limit or is not a file.');
    icon=fs.readFileSync(iconPath);
    if(!isValidPng256(icon))throw Error('Custom icon must be a 256x256 PNG.');
  } else {
    icon=createPng(accentColor,letter);
  }
  const props=[
    '# Generated by Warpvio Android QA builder; do not commit this file.',
    'applicationId='+propertiesEscape(applicationId),
    'appName='+propertiesEscape(appName),
    'siteUrl='+propertiesEscape(websiteUrl),
    'accentColor='+propertiesEscape(accentColor),
    'orientation='+propertiesEscape(nativeOrientation),
    ''
  ].join('\n');

  const output=path.join(baseDir,'generated');
  const drawable=path.join(baseDir,'app','src','main','res','drawable-nodpi');
  fs.mkdirSync(output,{recursive:true});
  fs.mkdirSync(drawable,{recursive:true});
  fs.writeFileSync(path.join(output,'app.properties'),props,{mode:0o600});
  fs.writeFileSync(path.join(drawable,'warpvio_icon.png'),icon);
  return {
    applicationId,appName,websiteUrl,accentColor,orientation:nativeOrientation,
    files:['generated/app.properties','app/src/main/res/drawable-nodpi/warpvio_icon.png']
  };
}

if(require.main===module){
  try{
    const flags=parseCli(process.argv.slice(2));
    const input={
      url:flags.url||process.env.APP_URL,
      name:flags.name||process.env.APP_NAME||'Warpvio QA Demo',
      accent:flags.accent||process.env.APP_ACCENT||'blue',
      orientation:flags.orientation||process.env.APP_ORIENTATION||'auto',
      icon:flags.icon||process.env.APP_ICON_FILE||undefined
    };
    const output=generate(input);
    console.log('Android QA configuration written:',output.appName);
    console.log('Site:',output.websiteUrl);
    console.log('Android package:',output.applicationId);
    console.log('Output: debug-key signed APK, developer QA only.');
  }catch(error){
    console.error('Android QA configuration error:',error.message);
    process.exitCode=1;
  }
}

module.exports={
  ACCENTS,ORIENTATIONS,validateUrl,validateName,
  validateAccent,validateOrientation,applicationIdFor,parseCli,
  propertiesEscape,generate
};
